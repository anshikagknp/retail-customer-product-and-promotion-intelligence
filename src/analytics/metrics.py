"""
Analytical metrics and descriptive segmentation calculations.
Strictly relies on explainable statistical and business metrics without black-box ML.
"""

import pandas as pd
import numpy as np


def calculate_rfm(df_hh: pd.DataFrame) -> pd.DataFrame:
    """
    Computes explainable Recency, Frequency, Monetary (RFM) scores and segments.
    - Recency: Based on recency_days (lower days = higher score)
    - Frequency: Based on basket_count (higher visits = higher score)
    - Monetary: Based on total_sales (higher spend = higher score)
    Scores range from 1 to 4 using quartiles.
    """
    rfm = df_hh.copy()

    # Quartiles (1 to 4)
    # Recency: lower recency_days gets higher score (4 is most recent)
    rfm["R_Score"] = pd.qcut(rfm["recency_days"], q=4, labels=[4, 3, 2, 1]).astype(int)
    
    # Frequency: higher basket_count gets higher score
    rfm["F_Score"] = pd.qcut(rfm["basket_count"].rank(method="first"), q=4, labels=[1, 2, 3, 4]).astype(int)
    
    # Monetary: higher total_sales gets higher score
    rfm["M_Score"] = pd.qcut(rfm["total_sales"].rank(method="first"), q=4, labels=[1, 2, 3, 4]).astype(int)

    # Combined RFM Score string (e.g., '444')
    rfm["RFM_Cell"] = (
        rfm["R_Score"].astype(str) + rfm["F_Score"].astype(str) + rfm["M_Score"].astype(str)
    )

    # Average Score
    rfm["RFM_Avg"] = ((rfm["R_Score"] + rfm["F_Score"] + rfm["M_Score"]) / 3.0).round(2)

    # Business Segment Definitions (intuitive and explainable)
    def assign_segment(row):
        r, f, m = row["R_Score"], row["F_Score"], row["M_Score"]
        if r >= 3 and f >= 3 and m >= 3:
            return "Champions / Core Loyal"
        elif r >= 3 and (f >= 2 or m >= 2):
            return "Active / Potential Loyalists"
        elif r <= 2 and f >= 3 and m >= 3:
            return "At Risk High-Value"
        elif r <= 2 and (f >= 2 or m >= 2):
            return "Needs Attention / Lapsing"
        elif r >= 3 and f == 1:
            return "Recent New / Occasional"
        else:
            return "Lapsed / Hibernating"

    rfm["Customer_Segment"] = rfm.apply(assign_segment, axis=1)

    return rfm


def calculate_pareto(df: pd.DataFrame, entity_col: str, value_col: str) -> pd.DataFrame:
    """
    Computes Pareto / Lorenz curve cumulative distribution.
    Shows the percentage of cumulative value generated by top entities.
    """
    grouped = df.groupby(entity_col)[value_col].sum().reset_index()
    grouped = grouped.sort_values(value_col, ascending=False).reset_index(drop=True)

    total_value = grouped[value_col].sum()
    total_entities = len(grouped)

    grouped["cumulative_value"] = grouped[value_col].cumsum()
    grouped["cumulative_value_pct"] = (grouped["cumulative_value"] / total_value * 100).round(2)
    grouped["entity_rank"] = np.arange(1, total_entities + 1)
    grouped["entity_pct"] = (grouped["entity_rank"] / total_entities * 100).round(2)

    return grouped


def calculate_department_summary(df_tx: pd.DataFrame, df_prod: pd.DataFrame) -> pd.DataFrame:
    """
    Calculates sales, units, basket penetration, and private label share across departments.
    """
    merged = df_tx.merge(df_prod[["PRODUCT_ID", "DEPARTMENT", "BRAND"]], on="PRODUCT_ID", how="left")
    
    total_sales = merged["SALES_VALUE"].sum()
    total_qty = merged["QUANTITY"].sum()
    total_baskets = merged["BASKET_ID"].nunique()

    dept = merged.groupby("DEPARTMENT").agg(
        total_sales=("SALES_VALUE", "sum"),
        total_quantity=("QUANTITY", "sum"),
        transaction_lines=("PRODUCT_ID", "count"),
        unique_baskets=("BASKET_ID", "nunique"),
        unique_products=("PRODUCT_ID", "nunique"),
        retail_discount=("RETAIL_DISC_AMOUNT", "sum"),
        coupon_discount=("COUPON_DISC_AMOUNT", "sum")
    ).reset_index()

    # Private label sales per department
    pvt_sales = merged[merged["BRAND"] == "Private"].groupby("DEPARTMENT")["SALES_VALUE"].sum().reset_index()
    pvt_sales = pvt_sales.rename(columns={"SALES_VALUE": "private_label_sales"})
    dept = dept.merge(pvt_sales, on="DEPARTMENT", how="left")
    dept["private_label_sales"] = dept["private_label_sales"].fillna(0)

    dept["sales_share_pct"] = (dept["total_sales"] / total_sales * 100).round(2)
    dept["quantity_share_pct"] = (dept["total_quantity"] / total_qty * 100).round(2)
    dept["basket_penetration_pct"] = (dept["unique_baskets"] / total_baskets * 100).round(2)
    dept["private_label_share_pct"] = (dept["private_label_sales"] / dept["total_sales"] * 100).round(2)
    dept["discount_depth_pct"] = (
        (dept["retail_discount"] + dept["coupon_discount"]) / (dept["total_sales"] + dept["retail_discount"] + dept["coupon_discount"]) * 100
    ).round(2)

    dept = dept.sort_values("total_sales", ascending=False).reset_index(drop=True)
    return dept

